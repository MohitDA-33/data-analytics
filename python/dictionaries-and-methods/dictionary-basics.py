# Dictionary and Dictionary Methods

# Dictionary, is used to store key-value pairs, each key is linked to a value seperated by comma(,).

student_1 = {
    "Name": "Mohit",   # Its a syntax of how you create a dictionary in python, to create a dictionary we use curlybraces{}.
    "City": "Delhi",
    "Company": "Meta"
}

print(student_1)

student_2 = dict(name = "Mohit", age = 22, city = "Delhi")   # You can also create a dictionary Using a dict() function.
print(student_2)

marks = {}   # This is how you create an empty dictionary.
print(marks)