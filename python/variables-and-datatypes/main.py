# Variables and Datatypes

# Integer (int, whole numbers)
a = 23
students = 100
orders = 45

print(a)
print(students)
print(orders)

# String (str, text data)
name = "Mohit"
city = "Delhi"
email = "example@gmail.com"

print(name)
print(city)
print(email)

# Float (float, decimal numbers)
price = 2999.99
rating = 4.5

print(price)
print(rating)

# Boolean (bool, True or False)
is_paid = False
is_active = True

print(is_paid)
print(is_active)

